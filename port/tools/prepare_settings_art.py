"""Prepare the in-game settings page's host-resolution art (run menu1, lane SETMENU1).

Writes port/res/menu/settings/*.png from the launcher's art folder (res/art of the launcher repo), shrunk to the
sizes the port ever draws them at (the originals are far larger and are NOT committed), plus the DS-lettering font
atlas the page's text renderer (hal/ui_text.cpp) draws from.

    python port/tools/prepare_settings_art.py --art <launcher res/art> --font <sm64ds_original.otf> [--out port/res/menu/settings]

parchment.png   the page's sheet tile (page_parchment)
title.png       the SETTINGS plank, lettered (page_title_settings)
back.png        the BACK plank, lettered (page_back)
key.png         the blank keycap (key_blank): ends stay, the middle stretches for a long name
plank.png       the tan wooden plank (play_base) used for the Reset button
dd_top/dd_mid/dd_bot.png and dd_arrow.png   the purple drop-down wood and its arrow
font.png        one 8-bit coverage atlas of the printable ASCII glyphs of the DS lettering font at 96 px per em
font_metrics.inc   the atlas's glyph table (a C initializer list, included by hal/ui_text.cpp)
"""
import argparse, os
from PIL import Image, ImageDraw, ImageFont

Image.MAX_IMAGE_PIXELS = None
EM = 96   # font pixels per em in the atlas


def fit(src, dst, w):
    im = Image.open(src).convert("RGBA")
    h = round(im.height * w / im.width)
    im = im.resize((w, h), Image.LANCZOS)
    im.save(dst, optimize=True)
    return im.size


def font_atlas(font_path, out_png, out_inc):
    f = ImageFont.truetype(font_path, EM)
    asc, desc = f.getmetrics()
    glyphs = []
    for c in range(32, 127):
        ch = chr(c)
        adv = f.getlength(ch)
        bb = f.getbbox(ch, anchor="ls")          # relative to the pen on the baseline
        if c == 32 or bb is None or bb[2] <= bb[0] or bb[3] <= bb[1]:
            glyphs.append((c, 0, 0, 0, 0, 0, 0, adv))
            continue
        pad = 2
        x0, y0, x1, y1 = bb[0] - pad, bb[1] - pad, bb[2] + pad, bb[3] + pad
        w, h = x1 - x0, y1 - y0
        m = Image.new("L", (w, h), 0)
        ImageDraw.Draw(m).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
        glyphs.append((c, x0, y0, w, h, m, 0, adv))
    # shelf pack, 1024 wide
    AW = 1024
    x = y = rowh = 0
    place = {}
    for g in glyphs:
        if not g[3]:
            continue
        w, h = g[3], g[4]
        if x + w + 1 > AW:
            x = 0; y += rowh + 1; rowh = 0
        place[g[0]] = (x, y)
        x += w + 1; rowh = max(rowh, h)
    AH = y + rowh + 1
    atlas = Image.new("L", (AW, AH), 0)
    for g in glyphs:
        if g[3]:
            atlas.paste(g[5], place[g[0]])
    atlas.save(out_png, optimize=True)
    with open(out_inc, "w", newline="\n") as o:
        o.write("/* generated by tools/prepare_settings_art.py: {ch, atlas x, y, w, h, bearing x, bearing y (from the baseline, up is negative), advance} in atlas pixels at %d px per em */\n" % EM)
        o.write("#define UI_FONT_EM %d\n#define UI_FONT_ASCENT %d\n#define UI_FONT_DESCENT %d\n#define UI_FONT_AW %d\n#define UI_FONT_AH %d\n" % (EM, asc, desc, AW, AH))
        o.write("static const UiGlyphSrc kGlyphSrc[] = {\n")
        for g in glyphs:
            c = g[0]
            if g[3]:
                px, py = place[c]
                o.write("    { %d, %d, %d, %d, %d, %d, %d, %.2ff },\n" % (c, px, py, g[3], g[4], g[1], g[2], g[7]))
            else:
                o.write("    { %d, 0, 0, 0, 0, 0, 0, %.2ff },\n" % (c, g[7]))
        o.write("};\n")
    return atlas.size


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--art", required=True)
    ap.add_argument("--font", required=True)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "res", "menu", "settings"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    A = lambda n: os.path.join(a.art, n)
    O = lambda n: os.path.join(a.out, n)
    print("parchment", fit(A("page_parchment.png"), O("parchment.png"), 350))
    print("title", fit(A("page_title_settings.png"), O("title.png"), 600))
    print("back", fit(A("page_back.png"), O("back.png"), 320))
    print("key", fit(A("key_blank.png"), O("key.png"), 300))
    print("plank", fit(A("play_base.png"), O("plank.png"), 700))
    print("dd_top", fit(A("dd_top.png"), O("dd_top.png"), 368))
    print("dd_mid", fit(A("dd_middle.png"), O("dd_mid.png"), 368))
    print("dd_bot", fit(A("dd_bottom.png"), O("dd_bot.png"), 368))
    print("dd_arrow", fit(A("dd_arrow.png"), O("dd_arrow.png"), 92))
    print("font", font_atlas(a.font, O("font.png"), O("font_metrics.inc")))


main()
