"""Regenerate hal/menu_pause_art_data.cpp (the pause menu art PNGs of res/menu/pause3 as C byte arrays, so the exe carries them) and
the id list hal/menu_pause_art_ids.h. Run after tools/prepare_pause_art.py:   python port/tools/embed_pause3_art.py"""
import os
here = os.path.dirname(os.path.abspath(__file__))
res = os.path.join(here, "..", "res", "menu", "pause3")
names = ["pk_resume", "pk_settings", "pk_exit", "pk_savequit", "pk_quitnosave", "pk_yesquit", "pk_nokeep", "title_blank", "tab_l", "tab_r",
         "star_got", "star_off", "coin_gold", "coin_red"]
out = ["/* menu_pause_art_data.cpp -- the pause menu art PNGs of res/menu/pause3 as bytes (tools/embed_pause3_art.py). Generated; do not edit. */"]
for n in names:
    d = open(os.path.join(res, n + ".png"), "rb").read()
    out.append("static const unsigned char k_%s[] = {" % n)
    for i in range(0, len(d), 32):
        out.append(",".join(str(b) for b in d[i:i + 32]) + ",")
    out.append("};")
out.append("struct PauseArt { const char *file; const unsigned char *data; unsigned len; };")
out.append("extern \"C\" const PauseArt g_pause_art[] = {")
for n in names:
    out.append("    { \"pause/%s.png\", k_%s, (unsigned)sizeof k_%s }," % (n, n, n))
out.append("};")
out.append("extern \"C\" const int g_pause_art_count = %d;" % len(names))
open(os.path.join(here, "..", "hal", "menu_pause_art_data.cpp"), "w", newline="\n").write("\n".join(out) + "\n")
ids = ["/* menu_pause_art_ids.h -- host image ids of the pause menu art (generated by tools/embed_pause3_art.py). */",
       "#ifndef MENU_PAUSE_ART_IDS_H", "#define MENU_PAUSE_ART_IDS_H", "enum {"]
for i, n in enumerate(names):
    ids.append("    MENU_IMG_P_%s = %d," % (n.upper(), 32 + i))
ids.append("    MENU_IMG_P_END = %d };" % (32 + len(names)))
ids.append("#endif")
open(os.path.join(here, "..", "hal", "menu_pause_art_ids.h"), "w", newline="\n").write("\n".join(ids) + "\n")
print(len(names), "images")
